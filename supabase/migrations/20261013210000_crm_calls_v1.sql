-- CRM Calls v1: every call attempt to a customer, its outcome, and the Kanban stage it leads to.
-- Reads follow RLS; writes only through crm_call_log, which is idempotent and audited.
--   view attempts: can_view_customers
--   log attempts:  can_view_customers + can_reply_chats (same as moving a Kanban card)

create table public.crm_call_attempts (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  client_id text not null references public.clients(id) on delete cascade,
  card_id uuid references public.crm_pipeline_cards(id) on delete set null,
  outcome text not null check (outcome in ('answered','no_answer','busy','voicemail','wrong_number','callback','converted','not_interested')),
  notes text check (char_length(notes) <= 2000),
  duration_seconds integer check (duration_seconds between 0 and 86400),
  callback_at timestamptz,
  from_stage_id uuid,
  to_stage_id uuid,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index crm_call_attempts_client_idx on public.crm_call_attempts(organization_id, client_id, created_at desc);
create index crm_call_attempts_callback_idx on public.crm_call_attempts(organization_id, callback_at) where callback_at is not null;

alter table public.crm_call_attempts enable row level security;
create policy crm_call_attempts_customers_select on public.crm_call_attempts for select to authenticated using (private.has_org_capability(organization_id, 'can_view_customers'));
revoke all on public.crm_call_attempts from anon, authenticated;
grant select on public.crm_call_attempts to authenticated;

-- p_attempt_id is generated by the caller, so a retried or double-clicked submit returns the
-- first attempt instead of logging the call twice.
-- Stage: p_stage_id wins; otherwise 'converted' goes to the pipeline's first won stage and
-- 'not_interested' to its first lost stage; every other outcome leaves the card where it is.
-- The move reuses crm_card_move, so it keeps the version check and its own audit entry.
create or replace function public.crm_call_log(
  p_attempt_id uuid,
  p_client_id text,
  p_outcome text,
  p_notes text default null,
  p_duration_seconds integer default null,
  p_callback_at timestamptz default null,
  p_card_id uuid default null,
  p_stage_id uuid default null,
  p_expected_version integer default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $function$
declare
  v_org uuid := private.current_organization_id();
  v_attempt public.crm_call_attempts;
  v_card public.crm_pipeline_cards;
  v_to uuid := p_stage_id;
begin
  if auth.uid() is null or v_org is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;
  if not (private.has_org_capability(v_org, 'can_view_customers') and private.has_org_capability(v_org, 'can_reply_chats')) then
    raise exception 'FORBIDDEN' using errcode='42501';
  end if;
  if p_attempt_id is null then raise exception 'ATTEMPT_ID_REQUIRED' using errcode='22023'; end if;

  select * into v_attempt from public.crm_call_attempts where id = p_attempt_id;
  if found then
    if v_attempt.organization_id <> v_org then raise exception 'FORBIDDEN' using errcode='42501'; end if;
    return jsonb_build_object('attempt', to_jsonb(v_attempt), 'card', null, 'replayed', true);
  end if;

  if p_outcome is null or p_outcome not in ('answered','no_answer','busy','voicemail','wrong_number','callback','converted','not_interested') then
    raise exception 'INVALID_OUTCOME' using errcode='22023';
  end if;
  if p_outcome = 'callback' and p_callback_at is null then raise exception 'CALLBACK_AT_REQUIRED' using errcode='22023'; end if;
  if not exists (select 1 from public.clients where id = p_client_id and organization_id = v_org) then
    raise exception 'CLIENT_NOT_FOUND' using errcode='P0002';
  end if;

  if p_card_id is not null then
    select * into v_card from public.crm_pipeline_cards where id = p_card_id and organization_id = v_org;
    if not found or v_card.client_id <> p_client_id then raise exception 'CARD_NOT_FOUND' using errcode='P0002'; end if;
    if v_to is null and p_outcome in ('converted','not_interested') then
      select id into v_to from public.crm_stages
       where pipeline_id = v_card.pipeline_id and kind = case p_outcome when 'converted' then 'won' else 'lost' end
       order by position limit 1;
    end if;
  elsif v_to is not null then
    raise exception 'CARD_REQUIRED_FOR_STAGE' using errcode='22023';
  end if;

  insert into public.crm_call_attempts(id, organization_id, client_id, card_id, outcome, notes, duration_seconds, callback_at, from_stage_id, to_stage_id, created_by)
  values (p_attempt_id, v_org, p_client_id, p_card_id, p_outcome, nullif(trim(p_notes), ''), p_duration_seconds, p_callback_at,
          v_card.stage_id, case when v_to is distinct from v_card.stage_id then v_to end, auth.uid())
  returning * into v_attempt;

  if v_attempt.to_stage_id is not null then
    v_card := public.crm_card_move(v_card.id, v_attempt.to_stage_id, coalesce(p_expected_version, v_card.version));
  end if;

  insert into public.audit_logs(user_id, actor_id, organization_id, action, resource_type, resource_id, metadata)
  values (auth.uid(), auth.uid(), v_org, 'crm.call.logged', 'crm_call_attempt', v_attempt.id::text,
          jsonb_build_object('client_id', p_client_id, 'card_id', p_card_id, 'outcome', p_outcome,
                             'from_stage_id', v_attempt.from_stage_id, 'to_stage_id', v_attempt.to_stage_id, 'callback_at', p_callback_at));

  return jsonb_build_object('attempt', to_jsonb(v_attempt), 'card', case when p_card_id is null then null else to_jsonb(v_card) end, 'replayed', false);
end;
$function$;

revoke all on function public.crm_call_log(uuid, text, text, text, integer, timestamptz, uuid, uuid, integer) from public, anon;
grant execute on function public.crm_call_log(uuid, text, text, text, integer, timestamptz, uuid, uuid, integer) to authenticated;
